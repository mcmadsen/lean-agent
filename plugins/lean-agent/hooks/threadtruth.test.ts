const OLD = '11111111-2222-3333-4444-555555555555'
const NEW = '66666666-7777-8888-9999-000000000000'
const S1 = 'aaaaaaaa-1111-2222-3333-444444444444'
const S2 = 'bbbbbbbb-1111-2222-3333-444444444444'
const S3 = 'cccccccc-1111-2222-3333-444444444444'
const ROOT = '/p'
const L = '/h/.lean-agent'
const T1 = `${L}/threads/t1`
const NOW = 10_000_000
const MIN = 60_000

type Row = Record<string, unknown>
const row = (o: Row = {}): Row => ({ sessionId: OLD, id: OLD.slice(0, 8), name: 't1 · fix login', cwd: T1, status: 'idle', state: 'idle', pid: 0, startedAt: 1, ...o })
const agent = (o: Row = {}) => parseAgents(JSON.stringify([{ sessionId: 'a', ...o }]))[0]!
const msg = (agoMin: number, text = 'a message') => JSON.stringify({ ts: NOW - agoMin * MIN, text }) + '\n'

// a thread t1 whose session is OLD, a scripted `claude`: --bg lists the new session (named by -n, or by `newName`), stop ends the process,
// rm answers `rm`; agents prints `rows`
function world(o: { rows?: Row[]; thread?: Row; inbox?: string; config?: unknown } = {}) {
  resetLocks()
  resetRequestCache()
  resetViewCache()
  resetThreadCache()
  const h = fakeHost(null)
  h.clock.t = NOW
  h.files.set(`${ROOT}/templates/thread.md`, '<!-- generated by lean-agent for thread {{id}} -->\nmodel: {{model}}, effort: {{effort}}\n# {{id}} {{title}}')
  h.files.set(`${ROOT}/templates/front-desk.md`, 'desk {{lean}}')
  h.files.set(`${T1}/thread.json`, JSON.stringify({ id: 't1', title: 'fix login', project: '', state: 'open', sid: OLD, created: 1, lastWake: 0, delivered: 0, model: 'sonnet', effort: 'high', ...o.thread }))
  h.files.set(`${T1}/brief.md`, 'fix the login bug\nmore detail\n')
  h.files.set(`${T1}/CLAUDE.md`, '<!-- generated by lean-agent for thread t1 -->\nmodel: haiku, effort: low\n# t1 fix login')
  if (o.inbox) h.files.set(`${T1}/inbox.jsonl`, o.inbox)
  if (o.config) h.files.set(`${L}/config.json`, JSON.stringify(o.config))
  const st = { rows: (o.rows ?? [row()]) as Row[], next: NEW, newState: 'working', newName: '' as string, rm: { exitCode: 0, stdout: '', stderr: '' } }
  h.claude.handler = (a: string[]) => {
    if (a[0] === '--bg') {
      if (!a.includes('--resume')) st.rows.push({ sessionId: st.next, id: st.next.slice(0, 8), name: st.newName || a[a.indexOf('-n') + 1], cwd: T1, status: 'busy', state: st.newState, pid: 77, startedAt: 2 })
      return { exitCode: 0, stdout: `started ${st.next}\n` }
    }
    if (a[0] === 'agents') return { exitCode: 0, stdout: JSON.stringify(st.rows) }
    if (a[0] === 'stop') {
      for (const r of st.rows) if (r.id === a[1]) Object.assign(r, { pid: 0, status: 'stopped', state: 'stopped' }) // the process is gone after a stop
      return { exitCode: 0, stdout: '' }
    }
    if (a[0] === 'rm') return st.rm
    return { exitCode: 0, stdout: '' }
  }
  const calls = (first: string) => h.claudeCalls().filter(x => x[0] === first)
  const starts = () => h.claudeCalls().filter(x => x[0] === '--bg' && !x.includes('--resume'))
  const resumes = () => h.claudeCalls().filter(x => x[0] === '--bg' && x.includes('--resume'))
  const thread = () => JSON.parse(h.files.get(`${T1}/thread.json`)!)
  return { h, st, calls, starts, resumes, thread, run: (i: any) => leanThread(h.host, ROOT, i.action === 'list' ? { verbose: true, ...i } : i) } // (the long list form)
}

// ---- 1. the truth about "running" ----------------------------------------------------------------------------------------
test('liveOf: state working, blocked or idle decides (a status that still says busy does not make an idle session running); else the status', () => {
  expect(liveOf(agent({ state: 'idle', status: 'busy', pid: 42 }))).toBe('idle')
  expect(liveOf(agent({ state: 'working', status: 'idle' }))).toBe('working')
  expect(liveOf(agent({ state: 'blocked', status: 'idle' }))).toBe('idle') // 1.0.27c: blocked + idle + no waitingFor = an idle session that waits for its next message (seen live after lean_ask)
  expect(liveOf(agent({ state: 'blocked', status: 'idle', waitingFor: 'permission: Bash(x)' }))).toBe('working') // an open prompt
  expect(liveOf(agent({ state: 'blocked', status: 'busy' }))).toBe('working')
  expect(liveOf(agent({ status: 'busy' }))).toBe('working')
  expect(liveOf(agent({ status: 'weird' }))).toBe('working') // an unknown word is never "idle": no session is replaced on a guess
  expect(liveOf(agent({ status: 'idle' }))).toBe('idle')
  expect(liveOf(agent({ status: 'done', state: 'done' }))).toBe('gone')
  expect(liveOf(undefined)).toBe('gone')
})

test('truthOf: running | idle (N unread) | stuck (unread for stuckMinutes) | done | parked; a session that waits for the user is never stuck', () => {
  const q = (...ago: number[]) => ago.map(m => ({ ts: NOW - m * MIN }))
  const t = (o: Record<string, unknown>) => truthOf({ threadState: 'open', now: NOW, queued: [], row: undefined, ...o } as any)
  const working = agent({ state: 'working', status: 'busy', pid: 42 })
  const idle = agent({ state: 'idle', status: 'busy', pid: 42 })
  expect(t({ row: working }).word).toBe('running')
  expect(t({ row: working, queued: q(3) }).word).toBe('running') // a fresh message: it reads it at its next tool call
  expect(t({ row: working, queued: q(12) })).toMatchObject({ word: 'stuck', unread: 1, text: 'stuck: 1 unread queued for 12 min, no tool call or inbox read' })
  expect(t({ row: idle })).toMatchObject({ word: 'idle', unread: 0, text: 'idle' })
  expect(t({ row: idle, queued: q(1, 2) })).toMatchObject({ word: 'idle', unread: 2, text: 'idle, 2 unread queued' })
  expect(t({ row: idle, queued: q(11) }).word).toBe('stuck') // an idle session never reads its queue either
  expect(t({ row: idle, queued: q(11), stuckMinutes: 20 }).word).toBe('idle') // config threads.stuckMinutes
  expect(t({ row: agent({ state: 'blocked', pid: 1 }), queued: q(60) }).word).toBe('running') // waits on the user's prompt
  expect(t({ row: agent({ status: 'busy', waitingFor: 'permission prompt' }), queued: q(60) }).word).toBe('running')
  expect(t({ row: undefined }).word).toBe('done')
  expect(t({ row: working, finished: true }).word).toBe('done')
  expect(t({ threadState: 'parked', row: working }).word).toBe('parked')
})

