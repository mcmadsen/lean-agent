"""doctor: slow-trace listing, one shared 'guide is current' check, and speed on a busy home."""
import os
import sys
import tempfile
import time
import unittest

SCRIPTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "plugins", "lean-agent", "scripts")
sys.path.insert(0, SCRIPTS)
import lean_slow  # noqa: E402


class SlowTraceListTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.old_env = os.environ.get("LEAN_AGENT_HOME")
        os.environ["LEAN_AGENT_HOME"] = os.path.join(self.tmp.name, ".lean-agent")
        self.addCleanup(lambda: os.environ.update({"LEAN_AGENT_HOME": self.old_env}) if self.old_env
                        else os.environ.pop("LEAN_AGENT_HOME", None))
        os.makedirs(lean_slow.folder())

    def trace(self, name, age_h, size=0):
        p = os.path.join(lean_slow.folder(), name)
        with open(p, "w") as fh:
            fh.write("Thread 0x1 (most recent call first):\n  File \"x.py\", line 1 in wait\n  File \"y.py\", line 2 in run\n")
            fh.write("pad\n" * size)
        t = time.time() - age_h * 3600
        os.utime(p, (t, t))
        return p

    def test_recent_listed_with_name_and_age_older_counted(self):
        self.trace("20260101T000000-doctor-11.txt", 2)
        self.trace("20250101T000000-runs-12.txt", 72)
        self.trace("20250101T000001-runs-13.txt", 96)
        lines = lean_slow.report_lines(3)
        self.assertEqual(len(lines), 2, lines)
        self.assertIn("20260101T000000-doctor-11.txt", lines[0])
        self.assertIn("logs/slow/", lines[0])
        self.assertIn("2h 0m ago", lines[0])
        self.assertNotIn("..txt", lines[0])
        self.assertTrue(lines[1].startswith("2 older slow trace(s)"), lines)

    def test_big_trace_is_not_read_whole(self):
        self.trace("20260101T000000-doctor-11.txt", 1, size=2_000_000)
        t0 = time.time()
        self.assertEqual(len(lean_slow.newest(3, 24)), 1)
        self.assertLess(time.time() - t0, 0.5)


class GuideCurrentTest(unittest.TestCase):
    def test_guide_written_anywhere_is_current_everywhere(self):
        import json
        import subprocess
        tmp = tempfile.mkdtemp()
        self.addCleanup(lambda: __import__("shutil").rmtree(tmp, ignore_errors=True))
        home, repo = os.path.join(tmp, "lh"), os.path.join(tmp, "beta")
        os.makedirs(home)
        os.makedirs(repo)
        with open(os.path.join(home, "projects.json"), "w") as fh:
            json.dump({"alpha": {"path": os.path.join(tmp, "alpha")}, "beta": {"path": repo}}, fh)
        code = ("import sys; sys.path.insert(0, %r); import lean_agent as L; %s")
        env = dict(os.environ, LEAN_AGENT_HOME=home, HOME=tmp)

        def run(cwd, stmt):
            r = subprocess.run([sys.executable, "-c", code % (SCRIPTS, stmt)], cwd=cwd, env=env,
                               capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr)
            return (r.stdout.strip().splitlines() or [""])[-1]

        # update's step (prepare_home) runs outside any project; doctor's check runs inside one
        run(tmp, "L.prepare_home()")
        out = run(repo, "print(L.guide_states(L.home('home')))")
        self.assertEqual(out, "{'guide': 'current', 'desk': 'current'}")
        # an outdated guide is reported stale by the same function and installed again by prepare_home
        guide = os.path.join(home, "home", "CLAUDE.md")
        with open(guide, "w") as fh:
            fh.write("<!-- lean-agent guide 0000000000 (generated by lean-agent; delete this line to stop updates) -->\nold")
        self.assertIn("'guide': 'stale'", run(repo, "print(L.guide_states(L.home('home')))"))
        run(tmp, "L.prepare_home()")
        self.assertEqual(run(repo, "print(L.guide_states(L.home('home')))"), "{'guide': 'current', 'desk': 'current'}")


class DoctorSpeedTest(unittest.TestCase):
    """doctor on a busy home (big logs, many traces/runs/threads, slow external tools) stays quick."""

    def build(self, tmp):
        import json
        home = os.path.join(tmp, "lh")
        for d in ("logs/slow", "running", "polls", "runs", "worktrees"):
            os.makedirs(os.path.join(home, d))
        line = "2026-01-01T00:00:00 INFO  startup: service start\n" + "2026-01-01T00:00:01 INFO  noise " + "x" * 200 + "\n"
        for name in ("logs/debug.log", "lock-holds.log"):
            with open(os.path.join(home, name), "w") as fh:
                fh.write(line * 60000)  # ~13 MB each
        for i in range(60):
            with open(os.path.join(home, "logs", "slow", f"2026010{i % 9}T0000{i:02d}-cmd-{i}.txt"), "w") as fh:
                fh.write("Thread 0x1 (most recent call first):\n  File \"x.py\", line 1 in wait\n" + "pad\n" * 20000)
        for i in range(400):
            with open(os.path.join(home, "runs", f"r{i}.json"), "w") as fh:
                json.dump({"id": f"r{i}", "status": "done", "prompt": "p" * 500}, fh)
        threads = {f"t{i}": {"title": f"thread {i}", "closed": True, "events": []} for i in range(80)}
        with open(os.path.join(home, "threads.json"), "w") as fh:
            json.dump({"threads": threads}, fh)
        bindir = os.path.join(tmp, "bin")
        os.makedirs(bindir)
        for tool in ("claude", "ps", "launchctl", "du", "security", "gh"):  # each external call is slow (0.6 s)
            with open(os.path.join(bindir, tool), "w") as fh:
                fh.write("#!/bin/sh\nsleep 0.6\n")
            os.chmod(os.path.join(bindir, tool), 0o755)
        return home, bindir

    def test_doctor_is_under_1_5_s_and_verbose_names_slow_checks(self):
        import shutil
        import subprocess
        tmp = tempfile.mkdtemp()
        self.addCleanup(lambda: shutil.rmtree(tmp, ignore_errors=True))
        home, bindir = self.build(tmp)
        env = dict(os.environ, LEAN_AGENT_HOME=home, HOME=tmp, PATH=bindir + ":/usr/bin:/bin", LEAN_AGENT_TEST="1")
        agent = os.path.join(SCRIPTS, "lean_agent.py")
        subprocess.run([sys.executable, agent, "doctor"], env=env, cwd=tmp, capture_output=True, text=True)  # warm .pyc
        t0 = time.time()
        r = subprocess.run([sys.executable, agent, "doctor", "--verbose"], env=env, cwd=tmp, capture_output=True, text=True)
        took = time.time() - t0
        self.assertIn("doctor:", r.stdout, r.stderr)
        self.assertIn("timing: total", r.stdout)
        self.assertLess(took, 1.5, r.stdout)


if __name__ == "__main__":
    unittest.main()
