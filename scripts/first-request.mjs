#!/usr/bin/env node
// What the FIRST request of a thread session carries, in tokens (chars / 4, rounded up: the estimator of overhead.ts), part by part, for a
// haiku / low one-step thread and a sonnet / high thread, with the lite setup (hooks/firstrequest.ts) off and on.
//   node scripts/first-request.mjs                          the table (parts the files hold are computed, the engine's are read from a recorded thread)
//   node scripts/first-request.mjs --tools-from <file>      the output of `claude plugin test` (hooks/toolbudget.test.ts prints "tool schemas, thread: ...")
//   node scripts/first-request.mjs --from tN                the thread whose context-parts.json (the engine's own count) gives the engine rows
//                                                           (default: the newest thread with a counted breakdown; none = "unknown")
//   node scripts/first-request.mjs --brief "<text>"         the brief of the small profile (default: a made-up one-step brief)
//   node scripts/first-request.mjs --check                  fail when a lite guide line no longer matches exactly one line of templates/thread.md,
//                                                           the report rule is cut, or the lite guide is not smaller (run by hooks/skills-contract.test.sh)
// Measured here: the thread guide (templates/thread.md, filled), the skills listing a thread gets, the agent listing (name + description + tools),
// the lean-agent tool schemas (from the spec output), the brief. NOT measurable by a file: the engine's system prompt and built-in tool schemas,
// other MCP servers, the project's own CLAUDE.md files and rules: read from the thread's context-parts.json when there is one, else "unknown".
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const plugin = join(here, '..', 'plugins', 'lean-agent')
if (!process.env.FIRST_REQUEST_CHILD) {
  const r = spawnSync(process.execPath, ['--experimental-strip-types', '--no-warnings', fileURLToPath(import.meta.url), ...process.argv.slice(2)], { stdio: 'inherit', env: { ...process.env, FIRST_REQUEST_CHILD: '1' } })
  process.exit(r.status ?? 1)
}
const { liteGuide, LITE_DROP, LITE_DEFERRED_TOOLS, REPORT_SENTENCE, isLite, oneStepBrief } = await import(pathToFileURL(join(plugin, 'hooks', 'firstrequest.ts')).href)

const arg = n => (process.argv.includes(n) ? process.argv[process.argv.indexOf(n) + 1] : undefined)
const tok = s => Math.ceil(s.length / 4)
const front = (text, key) => new RegExp(`^${key}:\\s*(.*)$`, 'm').exec(/^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? '')?.[1]?.trim() ?? ''

// ---- the guide: templates/thread.md as threads.ts threadClaudeMd fills it (no profile block, a model line) ----
const guideOf = (model, effort) => readFileSync(join(plugin, 'templates', 'thread.md'), 'utf8').replace(/<!-- profile -->\n([\s\S]*?)<!-- \/profile -->\n?/, '').replace(/\{\{(\w+)\}\}/g, (_, k) => ({ id: 't1', title: 'demo', project: 'demo', lean: '/home/u/.lean-agent', attribution: 'attribution: off - no Co-Authored-By trailers, no Claude-Session lines, no generated-with lines', model, effort })[k] ?? '')

if (process.argv.includes('--check')) {
  const full = guideOf('haiku', 'low')
  const lines = full.split('\n')
  const bad = []
  for (const p of LITE_DROP) {
    const n = lines.filter(l => l.startsWith(p)).length
    if (n !== 1) bad.push(`lite guide line "${p}" matches ${n} lines of templates/thread.md (must be exactly 1)`)
  }
  const lite = liteGuide(full)
  if (!lite.includes('lean_report')) bad.push('the lite guide has no lean_report')
  const rule = lines.find(l => l.includes(REPORT_SENTENCE))
  if (rule && !lite.includes(rule)) bad.push('the lite guide dropped the report rule line')
  if (tok(lite) >= tok(full) - 800) bad.push(`the lite guide saves only ${tok(full) - tok(lite)} tokens (at least 800 expected)`)
  if (!lite.includes(lines[0]) || !lite.split('\n')[0].startsWith('<!-- generated by lean-agent')) bad.push('the lite guide must keep its generated-by first line (refreshGuide relies on it)')
  if (bad.length) {
    console.error(`first-request check: ${bad.length} problem(s)\n- ${bad.join('\n- ')}`)
    process.exit(1)
  }
  console.log(`first-request check ok: ${LITE_DROP.length} lite lines match, guide ${tok(full)} -> ${tok(lite)} tokens`)
  process.exit(0)
}

// ---- the parts ----
const skillsListing = role => {
  const dir = join(plugin, 'skills')
  return readdirSync(dir).sort().flatMap(d => {
    const f = join(dir, d, 'SKILL.md')
    if (!existsSync(f)) return []
    const t = readFileSync(f, 'utf8')
    const roles = front(t, 'roles')
    if (roles && !roles.split(',').map(x => x.trim()).includes(role)) return []
    return [`- lean-agent:${front(t, 'name') || d}: ${front(t, 'description')}`]
  }).join('\n')
}
const agentListing = () => readdirSync(join(plugin, 'agents')).sort().map(f => {
  const t = readFileSync(join(plugin, 'agents', f), 'utf8')
  return `- lean-agent:${front(t, 'name')}: ${front(t, 'description')} (Tools: ${front(t, 'tools') || '*'})`
}).join('\n')

// the spec output: "tool schemas, thread: 3125 tokens (12500 chars) in 8 tools: lean_review 1200, lean_report 650, ...; deferred: ..."
let toolRows = null
const tf = arg('--tools-from')
if (tf) {
  const m = /tool schemas, thread: (\d+) tokens[^\n]*? tools: ([^;\n]*)/.exec(readFileSync(tf, 'utf8'))
  if (m) toolRows = Object.fromEntries(m[2].split(',').map(x => x.trim().split(' ')).filter(x => x.length === 2).map(([n, v]) => [n, Number(v)]))
}

// the engine's own count of a recorded thread (the mod writes it at the first turn end: ctxparts.ts)
const threads = join(homedir(), '.lean-agent', 'threads')
const counted = () => {
  const ids = arg('--from') ? [arg('--from')] : existsSync(threads) ? readdirSync(threads).filter(x => /^t\d+$/.test(x)) : []
  const recs = ids.flatMap(id => {
    try {
      const r = JSON.parse(readFileSync(join(threads, id, 'context-parts.json'), 'utf8'))
      return r?.first?.full && r.first.fixed > 0 ? [{ id, at: Number(r.at) || 0, p: r.first, request: r.request }] : []
    } catch {
      return []
    }
  })
  return recs.sort((a, b) => b.at - a.at)[0] ?? null
}
const ref = counted()

const SMALL = { name: 'haiku / low, one-step brief', model: 'haiku', effort: 'low', brief: arg('--brief') ?? 'In demo/README.md the word "recieve" is misspelled. Fix it to "receive" and tell me when it is done.' }
const BIGP = {
  name: 'sonnet / high, multi-step brief', model: 'sonnet', effort: 'high',
  brief: 'Add a --dry-run flag to the export command of the demo app.\n1. Find where the command parses its flags and add --dry-run.\n2. With it, print what would be written and write nothing; the existing tests must still pass.\n3. Add a test for the flag, update the README usage section and commit.\nWork in your own worktree and report when the branch is ready.',
}

function column(p, off = false) {
  const lite = !off && isLite({ enabled: true, model: p.model, effort: p.effort, brief: p.brief })
  const rows = []
  const add = (part, ours, v, note = '') => rows.push({ part, ours, v, note })
  add('a  engine system prompt + built-in tool schemas', false, ref ? ref.p.system + ref.p.tools : null, ref ? `engine count of ${ref.id}` : 'unknown: no counted thread here')
  const toolAll = toolRows ? Object.values(toolRows).reduce((a, b) => a + b, 0) : null
  const toolCut = toolRows ? LITE_DEFERRED_TOOLS.reduce((a, n) => a + (toolRows[n] ?? 0), 0) : null
  add('b  lean-agent tool schemas', true, toolAll === null ? (ref?.p.mcpServers?.['lean-agent'] ?? null) : lite ? toolAll - toolCut : toolAll, toolAll === null ? (ref ? `engine count of ${ref.id}` : 'unknown (--tools-from <spec output>)') : `chars/4 from the spec${lite ? ` (${LITE_DEFERRED_TOOLS.join(', ')} deferred)` : ''}`)
  const guide = guideOf(p.model, p.effort)
  add('c  thread guide (CLAUDE.md, report rule in it)', true, tok(lite ? liteGuide(guide) : guide), lite ? 'lite' : 'full')
  add('d1 skills listing (thread role)', true, tok(skillsListing('thread')), 'plugin skills the thread uses (the engine counts its whole inventory: ctxparts.ts)')
  add('d2 agent listing (9 plugin agents)', true, tok(agentListing()), 'name + description + tools')
  add('e1 memory index', true, 400, 'at most (cap config memory.indexTokens; 0 without items)')
  add('e2 project rules / CLAUDE.md files', false, ref ? Math.max(0, ref.p.memory - tok(guideOf('sonnet', 'high'))) : null, ref ? `engine memory row minus the guide, ${ref.id}` : 'unknown')
  add('f  brief (first prompt; handover only on a restart)', true, tok(p.brief), '')
  add('g  other MCP servers + instructions', false, ref ? Object.entries(ref.p.mcpServers ?? {}).filter(([s]) => s !== 'lean-agent').reduce((a, [, v]) => a + v, 0) + (ref.p.mcpInstr ?? 0) : null, ref ? `engine count of ${ref.id}` : 'unknown')
  return { p: off ? { ...p, name: `${p.name}, lite off` } : p, lite, rows }
}

const out = [`first request of a thread session, tokens (chars / 4); * = lean-agent's own (cut-able here), the rest is the engine's or the user's`]
const cols = [column(SMALL), column(SMALL, true), column(BIGP)]
const w = Math.max(...cols[0].rows.map(r => r.part.length))
out.push(`${'part'.padEnd(w)}  ${cols.map(c => c.p.name.padStart(c.p.name.length > 30 ? c.p.name.length : 30)).join('  ')}`)
for (let i = 0; i < cols[0].rows.length; i++) {
  out.push(`${cols[0].rows[i].part.padEnd(w)}${cols[0].rows[i].ours ? ' *' : '  '}${cols.map(c => String(c.rows[i].v === null ? 'unknown' : c.rows[i].v).padStart(Math.max(30, c.p.name.length))).join('  ')}`)
}
const sum = c => c.rows.reduce((a, r) => a + (r.v ?? 0), 0)
const sumOurs = c => c.rows.filter(r => r.ours).reduce((a, r) => a + (r.v ?? 0), 0)
out.push(`${'total (unknown rows count 0)'.padEnd(w)}  ${cols.map(c => String(sum(c)).padStart(Math.max(30, c.p.name.length))).join('  ')}`)
out.push(`${'of which ours (*)'.padEnd(w)}  ${cols.map(c => String(sumOurs(c)).padStart(Math.max(30, c.p.name.length))).join('  ')}`)
out.push(`lite detection: ${cols.map(c => `${c.p.name}: ${c.lite ? 'lite' : 'normal'}`).join('; ')}; one-step brief: small ${oneStepBrief(SMALL.brief)}, big ${oneStepBrief(BIGP.brief)}`)
out.push(`saved by lite (small profile): ${sumOurs(cols[1]) - sumOurs(cols[0])} tokens`)
for (const r of cols[0].rows) if (r.note) out.push(`  ${r.part.slice(0, 2).trim()}: ${r.note}`)
console.log(out.join('\n'))
